-- Checkout reservations become first-class rows (runs once per store schema).
--
-- order-service generates the reservation id before calling, so every step is idempotent and
-- addressable: a retried reserve returns the same result, a release can never put stock back
-- twice, and a reservation whose order never materialised (crash, timeout, failed commit) is
-- found and returned by the expiry job instead of holding stock forever.

create table stock_reservation (
    id            varchar(36)  primary key,               -- UUID chosen by order-service
    status        varchar(16)  not null,                  -- HELD | CONFIRMED | RELEASED
    lines         text         not null,                  -- JSON [{productVariantId, quantity}]
    coupon_code   varchar(64),
    customer_key  varchar(320),                           -- u:<userId> | e:<email>
    result        text         not null,                  -- JSON of the reservation response
    created_at    timestamptz  not null default now(),
    expires_at    timestamptz  not null,
    updated_at    timestamptz  not null default now()
);
create index idx_stock_reservation_held_expiry on stock_reservation (expires_at) where status = 'HELD';

-- One row per coupon use, per customer. Counted under a lock on the coupon row, so two
-- concurrent checkouts by the same customer cannot both slip under perUserLimit.
create table coupon_redemption (
    id              bigint generated by default as identity primary key,
    coupon_code     varchar(64)  not null,
    customer_key    varchar(320) not null,
    reservation_id  varchar(36)  not null unique references stock_reservation (id),
    created_at      timestamptz  not null default now()
);
create index idx_coupon_redemption_customer on coupon_redemption (coupon_code, customer_key);
