-- Adventure Dose commercial-service — async order-event plumbing
-- Idempotent consumer (processed_event) + Transactional Outbox (for OrderRejected).

create table processed_event (
    event_id     varchar(100) primary key,
    processed_at timestamptz  not null default now()
);

create table outbox (
    id             bigint        generated by default as identity primary key,
    aggregate_type varchar(64)   not null,
    aggregate_id   varchar(64)   not null,
    event_type     varchar(64)   not null,
    payload        varchar(8000) not null,
    created_at     timestamptz   not null default now(),
    published_at   timestamptz
);
create index idx_outbox_unpublished on outbox (published_at) where published_at is null;
