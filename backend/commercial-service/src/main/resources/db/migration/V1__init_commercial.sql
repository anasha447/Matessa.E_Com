-- Adventure Dose commercial-service — initial catalog schema (commercial DB)

-- Admin-managed category hierarchy; each category can carry a display image.
create table categories (
    id            bigint        generated by default as identity primary key,
    parent_id     bigint        references categories (id),   -- null = top-level (main category)
    name          varchar(255)  not null,
    slug          varchar(255)  not null unique,
    description   varchar(1000),
    image_url     varchar(1000),                              -- main display photo
    display_order int           not null default 0,
    active        boolean       not null default true
);
create index idx_categories_parent on categories (parent_id);

-- The product concept. Holds no stock.
create table products (
    id          bigint        generated by default as identity primary key,
    category_id bigint        not null references categories (id),
    name        varchar(255)  not null,
    slug        varchar(255)  not null unique,
    description varchar(4000),
    base_price  numeric(12, 2) not null,
    brand       varchar(255),
    active      boolean       not null default true,          -- soft delete
    created_at  timestamptz   not null default now()
);
create index idx_products_category on products (category_id);

-- The unit actually stocked and purchased.
create table product_variants (
    id             bigint        generated by default as identity primary key,
    product_id     bigint        not null references products (id),
    sku            varchar(100)  not null unique,
    size           varchar(50),
    color          varchar(50),
    price_override numeric(12, 2),                            -- null = use products.base_price
    stock_quantity int           not null default 0 check (stock_quantity >= 0),
    restock_level  int,
    active         boolean       not null default true,       -- soft delete
    version        bigint        not null default 0           -- @Version optimistic lock (anti-oversell)
);
create index idx_variants_product on product_variants (product_id);

-- Product- or variant-scoped image gallery.
create table product_images (
    id            bigint        generated by default as identity primary key,
    product_id    bigint        not null references products (id),
    variant_id    bigint        references product_variants (id),  -- null = general product photo
    url           varchar(1000) not null,
    alt_text      varchar(255),
    display_order int           not null default 0,
    is_primary    boolean       not null default false
);
create index idx_images_product on product_images (product_id);
create index idx_images_variant on product_images (variant_id);
