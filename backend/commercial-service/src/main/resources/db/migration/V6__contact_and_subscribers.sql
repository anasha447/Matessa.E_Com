-- Adventure Dose commercial-service — storefront "front desk" data: customer contact queries
-- and newsletter subscribers. Owned here because the subscriber flow mints coupons (which live
-- in this service); both tables are self-contained (no cross-service FK).

-- Contact query: a support message from the storefront contact form. Guests may submit; staff
-- (MANAGER/ADMIN) read and resolve.
create table contact_queries (
    id         bigint       generated by default as identity primary key,
    email      varchar(320) not null,
    query_type varchar(120) not null,
    message    text         not null,
    status     varchar(16)  not null default 'OPEN',   -- OPEN / RESOLVED
    created_at timestamptz  not null default now()
);
create index idx_contact_queries_created on contact_queries (created_at desc);

-- Newsletter subscriber: a guest who traded their email for a welcome coupon. Email is unique
-- (idempotent signup); coupon_code references a coupon minted in the coupons table.
create table subscribers (
    id          bigint       generated by default as identity primary key,
    email       varchar(320) not null unique,
    coupon_code varchar(64),
    source      varchar(40),
    created_at  timestamptz  not null default now()
);
create index idx_subscribers_created on subscribers (created_at desc);
