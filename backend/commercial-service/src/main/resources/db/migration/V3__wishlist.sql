-- Adventure Dose commercial-service — per-customer wishlist

create table wishlists (
    id      bigint generated by default as identity primary key,
    user_id bigint not null unique          -- one wishlist per user; ID ref -> user-service
);

create table wishlist_items (
    id                 bigint      generated by default as identity primary key,
    wishlist_id        bigint      not null references wishlists (id),
    product_variant_id bigint      not null references product_variants (id),
    added_at           timestamptz not null default now(),
    unique (wishlist_id, product_variant_id)   -- a variant appears at most once per wishlist
);
create index idx_wishlist_items_wishlist on wishlist_items (wishlist_id);
