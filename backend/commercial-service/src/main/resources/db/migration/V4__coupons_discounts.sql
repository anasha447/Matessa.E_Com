-- Adventure Dose commercial-service — coupons (code-driven) + discounts (automatic)

-- Coupon: shopper types a code at checkout. Has time window, usage limits, min spend.
create table coupons (
    id             bigint         generated by default as identity primary key,
    code           varchar(64)    not null unique,
    discount_type  varchar(20)    not null,                  -- PERCENTAGE / FIXED_AMOUNT
    discount_value numeric(12, 2) not null,
    min_spend      numeric(12, 2),
    max_uses       int,                                      -- total redemptions allowed (null = unlimited)
    used_count     int            not null default 0,
    per_user_limit int,
    valid_from     timestamptz    not null,
    valid_until    timestamptz    not null,
    active         boolean        not null default true
);

-- Discount: manager sets it on a product OR a category; auto-applies, no code.
-- A category discount cascades to the category's sub-branches (resolved in the service).
create table discounts (
    id          bigint         generated by default as identity primary key,
    product_id  bigint         references products (id),
    category_id bigint         references categories (id),
    type        varchar(20)    not null,                     -- PERCENTAGE / FIXED_AMOUNT
    value       numeric(12, 2) not null,
    valid_from  timestamptz    not null,
    valid_to    timestamptz    not null,
    active      boolean        not null default true,
    created_by  bigint         not null,                     -- ID ref -> user-service (manager)
    constraint chk_discount_target check (
        (product_id is not null and category_id is null) or
        (product_id is null and category_id is not null)
    )
);
create index idx_discounts_product on discounts (product_id);
create index idx_discounts_category on discounts (category_id);
