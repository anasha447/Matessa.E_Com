-- Adventure Dose order-service — initial schema (orders DB)

-- One cart per customer.
create table carts (
    id         bigint      generated by default as identity primary key,
    user_id    bigint      not null unique,          -- ID ref -> user-service
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table cart_items (
    id                 bigint generated by default as identity primary key,
    cart_id            bigint not null references carts (id),
    product_variant_id bigint not null,              -- ID ref -> commercial-service (NOT an FK)
    quantity           int    not null check (quantity > 0),
    unique (cart_id, product_variant_id)             -- a variant appears once per cart
);
create index idx_cart_items_cart on cart_items (cart_id);

-- A placed order. Payment + shipping folded in; coupon/address/totals are snapshots.
create table orders (
    id                        bigint         generated by default as identity primary key,
    user_id                   bigint         not null,           -- ID ref -> user-service
    order_number              varchar(40)    not null unique,
    status                    varchar(20)    not null,           -- OrderStatus
    subtotal                  numeric(12, 2) not null,
    discount_amount           numeric(12, 2) not null default 0,
    total                     numeric(12, 2) not null,
    coupon_code               varchar(64),                       -- snapshot
    shipping_address_snapshot varchar(2000)  not null,           -- JSON snapshot, not an FK
    payment_status            varchar(20)    not null,           -- PaymentStatus
    payment_method            varchar(20),                       -- PaymentMethod
    transaction_id            varchar(100),
    shipping_status           varchar(20)    not null,           -- ShippingStatus
    shipping_method           varchar(100),
    tracking_number           varchar(100),
    created_at                timestamptz    not null default now(),
    updated_at                timestamptz    not null default now(),
    version                   bigint         not null default 0   -- @Version optimistic lock
);
create index idx_orders_user on orders (user_id);
create index idx_orders_status on orders (status);

-- Everything here is frozen at purchase time.
create table order_items (
    id                    bigint         generated by default as identity primary key,
    order_id              bigint         not null references orders (id),
    product_variant_id    bigint         not null,               -- ID ref -> commercial-service
    product_name_snapshot varchar(255)   not null,
    sku_snapshot          varchar(100)   not null,
    unit_price_snapshot   numeric(12, 2) not null,
    quantity              int            not null check (quantity > 0)
);
create index idx_order_items_order on order_items (order_id);

-- Audit trail of status transitions.
create table order_status_history (
    id          bigint      generated by default as identity primary key,
    order_id    bigint      not null references orders (id),
    from_status varchar(20),
    to_status   varchar(20) not null,
    note        varchar(500),
    changed_by  bigint,                                          -- userId, or null for system
    changed_at  timestamptz not null default now()
);
create index idx_status_history_order on order_status_history (order_id);

-- Transactional Outbox: business row + outbox row in one tx; a poller publishes to Kafka.
create table outbox (
    id             bigint        generated by default as identity primary key,
    aggregate_type varchar(64)   not null,
    aggregate_id   varchar(64)   not null,
    event_type     varchar(64)   not null,
    payload        varchar(8000) not null,                       -- JSON event
    created_at     timestamptz   not null default now(),
    published_at   timestamptz                                   -- null = not yet published
);
create index idx_outbox_unpublished on outbox (published_at) where published_at is null;

-- Idempotent consumer: event ids already handled (e.g. OrderRejected).
create table processed_event (
    event_id     varchar(100) primary key,
    processed_at timestamptz  not null default now()
);
